#!/usr/bin/env python3
"""Read-only status of every per-model pipeline file, for the models in a
--models-file (default `reports/unique_models.txt`). Run it before the full
regeneration and after each step (docs/RUNBOOK-full-regeneration.md).

Per file it counts the models that have it, are missing it, or have it
**stale** -- older than a file it is built from (e.g. a `test_combined.py`
older than its `test_structural_full.py`, or a `test_super_suite.py` older
than its `test_crosshair.py`), by modification time. With --since it also
counts how many were written at or after that time, which confirms a step
really rewrote its files instead of skipping them.

It also checks that the interpreters the regeneration uses exist.

Writes nothing. Exits 1 if a listed model has no folder or lacks one of the
dataset's own inputs (python_code.py, the BUML source, .puml,
model_metadata.json with status "measured" and a difficulty_score,
code_structure.json, test_hypothesis.py) -- those can't be regenerated by
the test pipeline.

Stdlib only, any venv.

Usage:
    python scripts/check_pipeline_status.py [--models-file PATH]
        [--since 2026-10-20T08:00] [--examples N] [--dataset-dir PATH]
"""
from __future__ import annotations

import argparse
import datetime
import json
import platform
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common.buml import find_buml_file  # noqa: E402
from _common.io import add_common_io_args, read_model_names  # noqa: E402

BUML = "BUML source"
PUML = ".puml"
# (file, built from). Inputs are the dataset's own files; outputs are ours.
INPUTS = ["python_code.py", BUML, "code_structure.json", "test_hypothesis.py", "model_metadata.json"]
OUTPUTS = [
    (PUML, [BUML]),
    ("test_structural_full.py", [BUML, "python_code.py"]),
    ("test_combined.py", ["test_hypothesis.py", "test_structural_full.py"]),
    ("test_behavioral.py", [BUML, "python_code.py"]),
    ("test_crosshair.py", ["python_code.py", "code_structure.json"]),
    ("test_super_suite.py", ["test_combined.py", "test_behavioral.py", "test_crosshair.py"]),
    ("test_combined_green.py", ["test_combined.py"]),
]
VENVS = [".venv", ".venv-puml", ".venv-testgen"]


def locate(model_dir: Path, name: str) -> Path | None:
    if name == BUML:
        return find_buml_file(model_dir)
    if name == PUML:
        pumls = sorted(model_dir.glob("*.puml"))
        return pumls[0] if pumls else None
    path = model_dir / name
    return path if path.is_file() else None


def metadata_problem(path: Path) -> str | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError):
        return "unreadable"
    if data.get("status") != "measured":
        return f"status {data.get('status')!r}"
    if "difficulty_score" not in data:
        return "no difficulty_score"
    return None


def venv_python(repo_root: Path, venv: str) -> Path:
    if platform.system() == "Windows":
        return repo_root / venv / "Scripts" / "python.exe"
    return repo_root / venv / "bin" / "python"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_common_io_args(parser, __file__)
    parser.add_argument("--models-file", type=Path, default=None, help="Default: reports/unique_models.txt")
    parser.add_argument("--since", type=datetime.datetime.fromisoformat, default=None,
                        help="Also count files written at or after this local time, e.g. 2026-10-20T08:00")
    parser.add_argument("--examples", type=int, default=5)
    args = parser.parse_args()
    repo_root = Path(__file__).resolve().parent.parent
    models_file = args.models_file or args.reports_dir / "unique_models.txt"
    models = read_model_names(models_file)
    since = args.since.timestamp() if args.since else None

    print(f"{models_file}: {len(models)} models ({len(set(models))} distinct)")
    blocking = len(models) != len(set(models))

    missing_dirs = [m for m in models if not (args.dataset_dir / m).is_dir()]
    if missing_dirs:
        blocking = True
        print(f"  NO FOLDER in {args.dataset_dir}: {len(missing_dirs)}  {missing_dirs[:args.examples]}")

    present: dict[str, list[str]] = {name: [] for name in INPUTS + [o for o, _ in OUTPUTS]}
    missing: dict[str, list[str]] = {name: [] for name in present}
    stale: dict[str, list[str]] = {o: [] for o, _ in OUTPUTS}
    written_since: dict[str, int] = {name: 0 for name in present}
    bad_metadata: list[str] = []
    for model in models:
        model_dir = args.dataset_dir / model
        if not model_dir.is_dir():
            continue
        mtimes: dict[str, float] = {}
        for name in present:
            path = locate(model_dir, name)
            if path is None:
                missing[name].append(model)
                continue
            present[name].append(model)
            mtimes[name] = path.stat().st_mtime
            if since is not None and mtimes[name] >= since:
                written_since[name] += 1
            if name == "model_metadata.json":
                problem = metadata_problem(path)
                if problem:
                    bad_metadata.append(f"{model} ({problem})")
        for output, sources in OUTPUTS:
            if output in mtimes and any(mtimes.get(s, 0) > mtimes[output] for s in sources):
                stale[output].append(model)

    def row(name: str, required: bool) -> None:
        nonlocal blocking
        line = f"  {name:24} {len(present[name]):>7} {len(missing[name]):>8}"
        line += f" {len(stale[name]):>6}" if name in stale else f" {'':>6}"
        if since is not None:
            line += f" {written_since[name]:>14}"
        print(line)
        if missing[name] and required:
            blocking = True
        for label, names in (("missing", missing[name]), ("stale", stale.get(name, []))):
            if names:
                print(f"      {label}: {names[:args.examples]}")

    header = f"  {'file':24} {'present':>7} {'missing':>8} {'stale':>6}"
    if since is not None:
        header += f" {'written since':>14}"
    print("\nDataset inputs (must all be present):")
    print(header)
    for name in INPUTS:
        row(name, required=True)
    if bad_metadata:
        blocking = True
        print(f"  model_metadata.json not usable: {len(bad_metadata)}  {bad_metadata[:args.examples]}")
    print("\nPipeline outputs (missing = not built yet, stale = older than an input):")
    print(header)
    for output, _ in OUTPUTS:
        row(output, required=False)

    print("\nInterpreters:")
    for venv in VENVS:
        python = venv_python(repo_root, venv)
        print(f"  {venv:14} {'ok' if python.is_file() else 'MISSING'}  {python}")
        blocking = blocking or not python.is_file()

    print("\nBLOCKED -- fix the items above first." if blocking else "\nOK -- inputs complete.")
    sys.exit(1 if blocking else 0)


if __name__ == "__main__":
    main()
