#!/usr/bin/env python3
"""Build the clean, benchmarking-ready copy of the dataset from a split made
by `make_benchmark_split.py`. The research `Dataset/` is only read, never
changed; the copy is what the benchmarking repo clones.

Layout (file names are standardized, so the benchmark never has to search):

    <output-dir>/
      manifest.json             parameters, source commit, one entry per model
      README.md                 this layout, for whoever clones it
      train/<model>/ and test/<model>/, each holding:
        model.puml              the diagram (benchmark input)
        model_buml.py           the same model as BUML source
        python_code.py          reference implementation
        test_super_suite.py     the fixed test suite

`python_code.py` keeps its name because the test suite imports it by that
name; code generated by an LLM has to be saved under the same name to be
tested. Every file is checked before anything is written: a model missing
one aborts the export with the full list, so a copy is never half-built.

Usage:
    python scripts/export_benchmark_dataset.py --output-dir PATH
        [--split-report reports/benchmark_split.json] [--test-file test_super_suite.py]
        [--dataset-dir PATH] [--force]
"""
from __future__ import annotations

import argparse
import datetime
import json
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common.buml import find_buml_file  # noqa: E402
from _common.io import add_common_io_args  # noqa: E402

REFERENCE_CODE = "python_code.py"


def source_files(model_dir: Path, test_file: str) -> tuple[dict[str, Path], list[str]]:
    """{exported name: source path} for one model, plus what is missing."""
    pumls = sorted(model_dir.glob("*.puml"))
    buml = find_buml_file(model_dir)
    files = {
        "model.puml": pumls[0] if pumls else None,
        "model_buml.py": buml,
        REFERENCE_CODE: model_dir / REFERENCE_CODE,
        test_file: model_dir / test_file,
    }
    missing = [name for name, path in files.items() if path is None or not path.is_file()]
    return {name: path for name, path in files.items() if name not in missing}, missing


def source_commit(repo_root: Path) -> str | None:
    try:
        result = subprocess.run(["git", "rev-parse", "HEAD"], cwd=repo_root, capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    return result.stdout.strip() or None


def render_readme(manifest: dict) -> str:
    counts = manifest["counts"]
    return "\n".join([
        "# Benchmark dataset",
        "",
        f"Exported {manifest['exported_at']} from the BESSER dataset repo"
        + (f" (commit `{manifest['source_commit']}`)" if manifest["source_commit"] else "") + ".",
        f"{counts['train']} train and {counts['test']} test models, stratified by difficulty bucket "
        f"(train ratio {manifest['split']['train_ratio']}, seed {manifest['split']['seed']}). "
        "Models with byte-identical diagrams are kept on the same side.",
        "",
        "Each `train/<model>/` and `test/<model>/` folder holds:",
        "",
        "- `model.puml` -- the class diagram, the benchmark input",
        "- `model_buml.py` -- the same model as BUML source",
        f"- `{REFERENCE_CODE}` -- the reference implementation; generated code must use this file name",
        f"- `{manifest['test_file']}` -- the fixed test suite, passing on the reference implementation",
        "",
        "`manifest.json` lists every model with its difficulty score, bucket, split, duplicate group "
        "and original file names.",
        "",
    ])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_common_io_args(parser, __file__)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--split-report", type=Path, default=None,
                         help="Default: <reports-dir>/benchmark_split.json")
    parser.add_argument("--test-file", default="test_super_suite.py")
    parser.add_argument("--force", action="store_true", help="Replace an existing, non-empty output directory")
    args = parser.parse_args()

    dataset_dir = args.dataset_dir.resolve()
    output_dir = args.output_dir.resolve()
    if output_dir == dataset_dir or dataset_dir in output_dir.parents or output_dir in dataset_dir.parents:
        parser.error("--output-dir must be outside the dataset directory")
    if output_dir.exists() and any(output_dir.iterdir()) and not args.force:
        parser.error(f"{output_dir} is not empty (pass --force to replace it)")

    split_path = args.split_report or args.reports_dir / "benchmark_split.json"
    split = json.loads(split_path.read_text(encoding="utf-8"))
    assignments = split["assignments"]

    plan, problems = [], []
    for a in assignments:
        files, missing = source_files(dataset_dir / a["model"], args.test_file)
        if missing:
            problems.append(f"{a['model']}: missing {', '.join(missing)}")
        plan.append((a, files))
    if problems:
        print(f"Export aborted, {len(problems)} models are incomplete:")
        for line in problems[:50]:
            print(f"  {line}")
        if len(problems) > 50:
            print(f"  ... and {len(problems) - 50} more")
        sys.exit(1)

    if output_dir.exists():
        shutil.rmtree(output_dir)
    entries = []
    for a, files in plan:
        target = output_dir / a["split"] / a["model"]
        target.mkdir(parents=True)
        for name, source in files.items():
            shutil.copy2(source, target / name)
        entries.append({
            "model": a["model"], "split": a["split"], "bucket": a["bucket"],
            "difficulty_score": a["difficulty_score"], "puml_group": a["puml_group"],
            "path": f"{a['split']}/{a['model']}",
            "original_files": {name: source.name for name, source in files.items()},
        })

    repo_root = Path(__file__).resolve().parent.parent
    manifest = {
        "exported_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "source_commit": source_commit(repo_root),
        "split_report": str(split_path),
        "split": split["parameters"],
        "test_file": args.test_file,
        "counts": {"train": sum(e["split"] == "train" for e in entries),
                   "test": sum(e["split"] == "test" for e in entries)},
        "buckets": split["buckets"],
        "models": entries,
    }
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    (output_dir / "README.md").write_text(render_readme(manifest), encoding="utf-8")
    print(f"Exported {len(entries)} models ({manifest['counts']['train']} train, "
          f"{manifest['counts']['test']} test) to {output_dir}")


if __name__ == "__main__":
    main()
